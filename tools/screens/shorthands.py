"""Capture shorthands (owner, 2026-10-07: "can more shorthands be listed?").

A shorthand is a token typed at the line's start (a kind) or anywhere (a field marker). Each candidate is checked:
  clash    the token is itself a word a line could start with, so typing it would switch the kind by accident.
           Checked against SHORT_WORDS: English and Italian words of one to three letters (the only length a
           1-3 letter token can collide with), written out below; a built-in list, not a corpus count
  dup      two shorthands share a token
  prior    the symbol means something else in the reference apps (from _screens-sources/nl-capture-research.md):
           a habit a person brings from Todoist or TickTick
Then how many fit in the hint line: items at 12 px, glyph width 0.48 em (measured from the render, capture_opt),
over the sheet's 336 px inner width, separated by " · ".

    PYTHONUTF8=1 python tools/screens/shorthands.py
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "docs", "screens", "t1", "shorthands.md")

SHORT_WORDS = set("""
a i o an am as at be by do go he if in is it me my no of oh ok on or so to up us we ad ah eh hi ma pa ex
all and any are ask bad big but buy can car cat day did dog eat end few fix for fun get got had has her him his how
its job let lot man may new not now old one our out own pay put ran red run sad saw say see she sit six ten the too
top try two use was way who why yes yet you mum dad gym tea bus fly lab law log mix nap net odd off pet pin ran rid
row set sky sum tax tip toy van vet war web wet win won zip age air arm art bag bed bit box boy cup cut die dry due
e è a ad al ai da di de del in con per su tra fra il la le lo gli un uno una non che chi ci si se ne mi ti vi
ho ha hai fa fai va vai sto sta può qua là già più poi ora oggi ieri sì no né ma ed od io tu lui lei noi voi
mio tuo suo bar per tre due sei tè re ok sei dio uva ape oro età
""".split())

# kind: token, kind, example, prior meaning in the references
KINDS = [
    ("td", "task", "td call mum fri", ""),
    ("ev", "event", "ev dentist tomorrow 9am", ""),
    ("rm", "reminder", "rm take meds 21:00", ""),
    ("lg", "tracker or habit log", "lg water 2", ""),
    ("j", "journal line", "j slept badly", ""),
    ("t", "timer (no duration) or time log (with one)", "t reading · t reading 30m", ""),
    ("ck", "Check-in", "ck energy 2", ""),
    ("ld", "ledger", "ld masking high", ""),
    # rejected candidates, kept so the check shows why
    ("ci", "Check-in (rejected)", "ci energy 2", ""),
    ("log", "log (rejected)", "log water 2", ""),
    ("re", "reminder (rejected)", "re take meds", ""),
]
# field markers, typed anywhere: token, field, example, prior meaning in the references
FIELDS = [
    ("#", "label", "#health", "TickTick: tag; Todoist: project"),
    ("!", "reminder offset", "!10m", "Todoist: reminder; TickTick: priority"),
    ("@", "calendar, or the tracker a log goes to", "@personal · @water", "Todoist: label (being retired); TickTick: assignee"),
    ("^", "page the item links to", "^garden plan", "TickTick: list"),
    ("~", "duration", "~30m", ""),
    ("*", "repeat", "*every 6 months", "TickTick: date"),
]
EM, FONT, WIDTH, SEP = 0.48, 12, 336, " · "


def clash(token):
    return token.lower() in SHORT_WORDS


def fit(items):
    used, n = 0.0, 0
    for i, it in enumerate(items):
        w = (len(it) + (len(SEP) if i else 0)) * EM * FONT
        if used + w > WIDTH:
            break
        used, n = used + w, n + 1
    return n


def main():
    toks = [k[0] for k in KINDS] + [f[0] for f in FIELDS]
    dups = {x for x in toks if toks.count(x) > 1}
    lines = ["# Capture shorthands", "", "Generated by `tools/screens/shorthands.py` (its docstring states the checks).", "",
             "## Kinds (typed at the line's start, then a space)", "", "| Token | Kind | Example | Clashes with a word | Status |", "|---|---|---|---|---|"]
    kept = []
    for tok, kind, ex, prior in KINDS:
        c = clash(tok)
        status = "rejected" if c or "rejected" in kind else "kept"
        if status == "kept":
            kept.append("%s %s" % (tok, kind.split(" (")[0].split(" or ")[0]))
        lines.append("| `%s` | %s | `%s` | %s | %s |" % (tok, kind.replace(" (rejected)", ""), ex, "yes" if c else "no", status))
    lines += ["", "## Field markers (typed anywhere)", "", "| Marker | Field | Example | Means elsewhere |", "|---|---|---|---|"]
    for tok, field, ex, prior in FIELDS:
        lines.append("| `%s` | %s | `%s` | %s |" % (tok, field, ex, prior or "nothing in the references"))
    items_kinds = ["j journal", "lg log", "t timer", "ck Check-in", "td task", "ev event", "rm reminder", "ld ledger"]
    items_fields = ["# label", "! reminder", "@ calendar", "^ page", "~ duration", "* repeat"]
    n1 = fit(items_kinds)
    lines += ["", "## How many fit in the hint", "",
              "- One line at 12 px holds **%d of the 8 kinds** (%s)." % (n1, " · ".join(items_kinds[:n1])),
              "- The 6 field markers fit **%d per line**." % fit(items_fields),
              "- All 14 need **%d lines** of hint." % (-(-len(" · ".join(items_kinds + items_fields)) * EM * FONT // WIDTH)),
              "", "Duplicate tokens: %s." % (", ".join(sorted(dups)) or "none")]
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
