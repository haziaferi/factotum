"""The shared state set (decision 15, Q4): done, skipped, due soon, attention. Writes docs/screens/t0/states.md.

Owner (2026-10-06): one state set shared by every module; its colours are reserved, so no palette may use
them for anything else. Red is forbidden everywhere.

So a state colour is a cost: every lexicon colour within dE 15 of it is lost to the palettes. Candidates per
state come from conventional families (done: a calm tick; due soon: a mild nudge; attention: the strongest
non-red signal), each solved per theme to 4.5:1 on the ground so it can carry text. "neutral" means the
state is drawn in ink (a filled tick, a dimmed row) and reserves no hue. Skipped is always neutral (no
judgement), and so costs nothing.

Every combination is scored: lexicon colours lost (lower), the states' own separation (dE >= 20, and >= 10
under protanopia and deuteranopia, required), and attention's salience (its chroma must be the set's
highest, required). Ties go to fewer reserved hues.

    PYTHONUTF8=1 python tools/screens/state_colours.py
"""
import importlib.util
import itertools
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
T0 = os.path.join(ROOT, "docs", "screens", "t0")
spec = importlib.util.spec_from_file_location("pg", os.path.join(HERE, "palette_groups.py"))
pg = importlib.util.module_from_spec(spec)
spec.loader.exec_module(pg)
cs = pg.cs

# family -> (hue range, chroma); hue steps of 10 inside each range
FAMILIES = {
    "done": {"neutral": None, "green": ((135, 155), 0.10), "teal": ((175, 205), 0.09), "blue": ((235, 255), 0.10)},
    "due": {"neutral": None, "ochre": ((75, 95), 0.11), "olive": ((105, 120), 0.10), "slate": ((240, 260), 0.06)},
    "attention": {"orange": ((45, 60), 0.15), "magenta": ((335, 350), 0.15), "violet": ((295, 310), 0.15), "ochre": ((70, 85), 0.15)},
}
STATES = ["done", "due", "attention"]


def solve(h, C, theme):
    return pg.solve_accent(h, C, theme, 4.5)


def candidates(state):
    out = []
    for fam, spec_ in FAMILIES[state].items():
        if spec_ is None:
            out.append({"state": state, "family": "neutral", "hue": None, "light": None, "dark": None})
            continue
        (lo, hi), C = spec_
        for h in range(lo, hi + 1, 10 if hi > lo else 1):
            out.append({"state": state, "family": fam, "hue": h, "C": C, "light": solve(h, C, "light"), "dark": solve(h, C, "dark")})
    return out


def lexicon_pool():
    """Every chromatic colour the lexicon could give a palette, after the owner's hue rules."""
    src = json.load(open(os.path.join(T0, "palette-sources.json"), encoding="utf-8"))
    pool = set()
    for e in src["entries"]:
        for p in e["pairs"]:
            for role, hx in p.get("light", {}).items():
                if role in ("surface", "text", "bg", "mid", "muted"):
                    continue
                L, C, h = pg.hex_to_oklch(hx)
                cls = pg.hue_class(L, C, h)
                if C >= 0.03 and not cls.startswith("forbidden"):
                    pool.add(hx.upper())
    # compare at the lightness palettes will actually use: each colour re-solved like an accent
    return sorted(pool), {hx: {t: pg.solve_accent(pg.hex_to_oklch(hx)[2], max(0.06, min(pg.hex_to_oklch(hx)[1], 0.11)), t, 5.0)
                               for t in ("light", "dark")} for hx in pool}


def score(combo, pool, adapted):
    chromatic = [c for c in combo if c["hue"] is not None]
    for a, b in itertools.combinations(chromatic, 2):
        for t in ("light", "dark"):
            if pg.de(a[t], b[t]) < 20:
                return None
            for kind in ("protanopia", "deuteranopia"):
                if pg.de(cs.simulate_cvd(a[t], kind), cs.simulate_cvd(b[t], kind)) < 10:
                    return None
    att = next(c for c in combo if c["state"] == "attention")
    if any(c is not att and c.get("C", 0) >= att["C"] for c in chromatic):
        return None
    lost = sum(any(pg.de(adapted[hx][t], c[t]) < 15 for c in chromatic for t in ("light", "dark")) for hx in pool)
    return {"lost": lost, "reserved": len(chromatic)}


def main():
    pool, adapted = lexicon_pool()
    rows = []
    for combo in itertools.product(*(candidates(s) for s in STATES)):
        sc = score(combo, pool, adapted)
        if sc:
            rows.append((sc["lost"], sc["reserved"], combo))
    rows.sort(key=lambda r: (r[0], r[1]))
    out = ["# Shared state colours", "", "Generated by `tools/screens/state_colours.py` (rules in its docstring).", "",
           "%d lexicon colours could go into a palette. Each state set below reserves its colours: the lexicon colours within ΔE 15 of a state colour are lost." % len(pool),
           "Skipped is neutral in every set. Feasible sets: %d." % len(rows), "",
           "| Lost | Done | Due soon | Attention |", "|---|---|---|---|"]
    fmt = lambda c: "neutral (ink)" if c["hue"] is None else "%s h%d · %s / %s" % (c["family"], c["hue"], c["light"], c["dark"])
    seen = set()
    for lost, _, combo in rows:
        key = tuple(c["family"] for c in combo)
        if key in seen:
            continue
        seen.add(key)
        out.append("| %d | %s |" % (lost, " | ".join(fmt(c) for c in combo)))
        if len(seen) >= 12:
            break
    with open(os.path.join(T0, "states.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")
    return rows, out


if __name__ == "__main__":
    rows, out = main()
    print("\n".join(out))
