"""Writes docs/screens/t0/reference.md from reference.json: one row per app and form factor, with the
step cost of every job (reference-protocol.md). 'n/a' = the app does not do the job; '?' = not found.

    python tools/screens/reference_table.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "docs", "screens", "t0", "reference.json")
OUT = os.path.join(ROOT, "docs", "screens", "t0", "reference.md")
JOBS = ["J1", "J2", "J4", "J5", "J6", "J7", "J8", "J9", "J10"]


def cell(job):
    if not isinstance(job, dict):
        return "n/a"
    if job.get("cost") is None:
        return "?"
    return "%d%s" % (job["cost"], "*" if job.get("from_anywhere") else "")


def fixed_count(dest):
    """Fixed navigation entries: everything in the record's destinations except the user's own lists."""
    n = 0
    for key, value in dest.items():
        if key in ("user", "user_sections", "list") or not isinstance(value, list):
            continue
        n += len(value)
    return n


records = json.load(open(SRC, encoding="utf-8"))["records"]
rows = sorted(records, key=lambda r: (r["form"], r["app"]))
lines = [
    "# Reference apps: navigation measured",
    "",
    "Generated by `tools/screens/reference_table.py` from `reference.json` (%d records). The method is in `reference-protocol.md`, and the jobs are those of `jobs.md`." % len(records),
    "",
    "**How to read the cells**",
    "",
    "- A number is the steps from the app's start screen to where the job is done.",
    "- **\\*** means the same cost from anywhere in the app.",
    "- **n/a** means the app does not do the job.",
    "- **?** means the control was not found.",
    "- **Fixed** counts the navigation entries the app always shows: bars, rails, drawers and menus, but not the user's own lists.",
    "",
    "| App | Form | Fixed | %s | Pattern |" % " | ".join(JOBS),
    "|---|---|---|%s|---|" % "|".join("---" for _ in JOBS),
]
for r in rows:
    lines.append("| %s | %s | %d | %s | %s |" % (
        r["app"], r["form"], fixed_count(r["destinations"]),
        " | ".join(cell(r["jobs"].get(j)) for j in JOBS), r["pattern"].split(";")[0]))
lines += [
    "",
    "**Not measured:**",
    "",
    "- Google Calendar on the phone: it has no launcher entry and is probably disabled.",
    "- Logseq and Joplin on the phone: Aurora could not install them.",
    "- Capacities and Amie: not on winget.",
    "- Things 3: iOS and macOS only.",
    "",
]
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print(OUT)
